// Measures bright cluster-member galaxies in the hero image for the lens model
// in src/lib/lens.ts. The galaxies are seeded by eye (SEEDS, in pixels of a
// 1000-px-wide copy of the image); the script snaps each seed to the nearest
// peak, drops any that turn out faint or orange (lensed background galaxies),
// and measures a brightness used to scale its mass.
// Run from the project root:  node scripts/find-members.mjs [debug.png]
// Writes src/data/lens-members.json. Positions are fractions of the image.
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';

const SRC = 'src/assets/abell-s1063-webb.jpg';
const BCG = { x: 0.5749, y: 0.5018 }; // keep in step with src/lib/lens.ts
const W = 1000;
// prettier-ignore
const SEEDS = [
  [335,690],[650,655],[695,612],[585,715],[670,715],[783,491],[500,608],[240,410],[270,765],
  [405,467],[490,275],[495,515],[462,492],[555,430],[530,415],[588,476],[558,481],[625,535],
  [660,523],[683,507],[700,510],[755,440],[688,370],[742,405],[812,422],[826,352],[800,288],
  [675,283],[632,282],[566,262],[628,325],[605,597],[566,580],[540,570],[525,570],[625,577],
  [755,580],[800,590],[808,633],[805,685],[790,705],[765,750],[750,783],[665,795],[570,800],
  [545,740],[490,753],[440,627],[362,648],[355,527],[365,540],[310,645],[870,478],[850,510],
  [875,705],[925,440],[215,395],[590,770],[445,345],[425,355],
];

const meta = await sharp(SRC).metadata();
const H = Math.round((W * meta.height) / meta.width);
const data = await sharp(SRC).resize(W, H).removeAlpha().raw().toBuffer();
const lum = new Float32Array(W * H);
for (let p = 0; p < W * H; p++) lum[p] = 0.3 * data[3 * p] + 0.5 * data[3 * p + 1] + 0.2 * data[3 * p + 2];
const fine = await sharp(Buffer.from(Uint8Array.from(lum, (v) => Math.min(255, v))), { raw: { width: W, height: H, channels: 1 } })
  .blur(1.5).extractChannel(0).raw().toBuffer();
if (fine.length !== W * H) throw new Error('unexpected channel count');

const cx = BCG.x * W;
const cy = BCG.y * H;
const members = [];
const dropped = [];
for (const [sx, sy] of SEEDS) {
  // Snap to the brightest smoothed pixel near the seed.
  let x = sx, y = sy, best = -1;
  for (let dy = -9; dy <= 9; dy++)
    for (let dx = -9; dx <= 9; dx++) {
      const v = fine[(sy + dy) * W + sx + dx] - 0.4 * Math.hypot(dx, dy);
      if (v > best) { best = v; x = sx + dx; y = sy + dy; }
    }
  const p = y * W + x;
  // Colour in a ring, where bright cores are not saturated.
  let r = 0, b = 0;
  for (let dy = -8; dy <= 8; dy++)
    for (let dx = -8; dx <= 8; dx++) {
      const d = dx * dx + dy * dy;
      if (d < 16 || d > 64) continue;
      r += data[3 * (p + dy * W + dx)]; b += data[3 * (p + dy * W + dx) + 2];
    }
  const red = r / Math.max(1, b);
  // Brightness above the sky further out.
  const ring = [];
  for (let k = 0; k < 32; k++) {
    const t = (k / 32) * 2 * Math.PI;
    ring.push(lum[Math.round(y + 24 * Math.sin(t)) * W + Math.round(x + 24 * Math.cos(t))]);
  }
  ring.sort((u, w) => u - w);
  const bg = ring[8];
  let flux = 0;
  for (let dy = -10; dy <= 10; dy++)
    for (let dx = -10; dx <= 10; dx++) if (dx * dx + dy * dy <= 100) flux += Math.max(0, lum[p + dy * W + dx] - bg);
  if (fine[p] < 120 || red > 1.32 || Math.hypot(x - cx, y - cy) < 14 || members.some((m) => Math.hypot(m.x - x, m.y - y) < 10)) {
    dropped.push([sx, sy, Math.round(fine[p]), red.toFixed(2)]);
    continue;
  }
  members.push({ x, y, flux });
}
members.sort((a, b) => b.flux - a.flux);
const lref = members[Math.floor(members.length * 0.25)].flux; // a bright member
const out = {
  note: 'Generated by scripts/find-members.mjs. x, y: fraction of image width/height; l: brightness relative to a bright member.',
  members: members.map((m) => ({ x: +(m.x / W).toFixed(4), y: +(m.y / H).toFixed(4), l: +(m.flux / lref).toFixed(3) })),
};
writeFileSync('src/data/lens-members.json', JSON.stringify(out) + '\n');
console.log(`members kept: ${members.length}; dropped seeds:`, JSON.stringify(dropped));
console.log('l range', out.members[0].l, out.members.at(-1).l);

if (process.argv[2]) {
  const marks = members.map((m) => `<circle cx="${m.x}" cy="${m.y}" r="${4 + 7 * Math.sqrt(m.flux / lref)}" fill="none" stroke="#0ff" stroke-width="1.2"/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">${marks}</svg>`;
  await sharp(SRC).resize(W, H).composite([{ input: Buffer.from(svg) }]).png().toFile(process.argv[2]);
}
